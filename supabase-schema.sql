create table if not exists public.maintenance_requests (
 id bigint generated by default as identity primary key,
 title text not null check (char_length(title) between 1 and 120),
 location text not null check (char_length(location) between 1 and 100),
 description text not null check (char_length(description) between 1 and 2000),
 status text not null default 'submitted' check (status in ('submitted','in_progress','completed')),
 created_at timestamptz not null default now(),
 archived_at timestamptz
);

alter table public.maintenance_requests enable row level security;
-- No public policies: the server-only service-role key is privileged and bypasses RLS.
